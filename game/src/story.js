export function computeMissionRating(mission, elapsedSec, damageTaken) {
  if (!mission) return 'B';
  if (elapsedSec <= mission.ratingGold.maxTime && damageTaken <= mission.ratingGold.maxDamage) {
    return 'G';
  }
  if (elapsedSec <= mission.ratingSilver.maxTime && damageTaken <= mission.ratingSilver.maxDamage) {
    return 'S';
  }
  return 'B';
}

export function getMissionById(id) {
  return STORY_MISSIONS.find((m) => m.id === id) || null;
}
